/**
 * Matches a free-text crop query against an entry's canonical name, its
 * aliases, and the local name inside a parenthetical suffix ("Sorghum (Jowar)"
 * also answers to "jowar").
 */
export function cropMatchesQuery(
  entry: CropKnowledgeEntry,
  query: string
): boolean {
  const needle = query.trim().toLowerCase();
  if (!needle) return false;

  if (entry.name.toLowerCase().includes(needle)) return true;
  if (entry.aliases?.some((alias) => alias.toLowerCase().includes(needle))) {
    return true;
  }

  const bracketed = entry.name.match(/\(([^)]+)\)/);
  if (!bracketed) return false;

  return bracketed[1]
    .split('/')
    .some((part) => part.trim().toLowerCase().includes(needle));
}

export function findCropInKnowledgeBase(
  cropName: string
): CropKnowledgeEntry | undefined {
  return CROP_DB.find((entry) => cropMatchesQuery(entry, cropName));
}
